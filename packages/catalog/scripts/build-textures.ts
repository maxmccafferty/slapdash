/**
 * Download the CC0 texture sets listed in `textures/manifest.json`, encode them to KTX2
 * and regenerate `textures/ATTRIBUTION.md`. Run by hand, not in CI; the outputs are
 * committed so nobody else needs the tools.
 *
 *   pnpm --filter @slapdash/catalog textures            # every set
 *   pnpm --filter @slapdash/catalog textures osb cmu    # just these sets
 *
 * Needs the Khronos KTX-Software `ktx` CLI (v4.3+) on PATH, or its path in `$KTX`, and
 * `unzip` for ambientCG downloads. Sources are downloaded into a fresh temp directory
 * outside the repo; nothing in it is executed.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { zTextureManifest, type TextureMap, type TextureSet } from '../src/textures.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', 'textures');
const MAX_FILE_BYTES = 1.5 * 1024 * 1024;
const MAX_TOTAL_BYTES = 35 * 1024 * 1024;
const KTX = process.env.KTX ?? 'ktx';

/** `ktx create` options per map: sRGB colour as BasisLZ, normals as UASTC + zstd, the rest as linear single-channel BasisLZ. */
const ENCODE: Record<TextureMap, string[]> = {
  color: ['--format', 'R8G8B8_SRGB', '--encode', 'basis-lz', '--generate-mipmap'],
  normal: [
    '--format', 'R8G8B8_UNORM', '--assign-tf', 'linear', '--encode', 'uastc',
    '--uastc-rdo', '--uastc-rdo-l', '1.5', '--zstd', '18', '--generate-mipmap', '--normal-mode',
  ],
  roughness: ['--format', 'R8_UNORM', '--assign-tf', 'linear', '--encode', 'basis-lz', '--generate-mipmap'],
  ao: ['--format', 'R8_UNORM', '--assign-tf', 'linear', '--encode', 'basis-lz', '--generate-mipmap'],
  metalness: ['--format', 'R8_UNORM', '--assign-tf', 'linear', '--encode', 'basis-lz', '--generate-mipmap'],
};

/** Poly Haven map names in its files API. */
const POLYHAVEN_MAP: Record<TextureMap, string> = {
  color: 'Diffuse',
  normal: 'nor_gl',
  roughness: 'Rough',
  ao: 'AO',
  metalness: 'Metal',
};

/** ambientCG file-name suffixes inside the 1K-JPG zip. */
const AMBIENTCG_MAP: Record<TextureMap, string> = {
  color: 'Color',
  normal: 'NormalGL',
  roughness: 'Roughness',
  ao: 'AmbientOcclusion',
  metalness: 'Metalness',
};

function fail(message: string): never {
  console.error(message);
  process.exit(1);
}

function checkKtx(): void {
  try {
    execFileSync(KTX, ['--version'], { stdio: 'pipe' });
  } catch {
    fail(
      `Can't run "${KTX}". Install KTX-Software v4.3 or later (https://github.com/KhronosGroup/KTX-Software/releases; ` +
        'the macOS .pkg puts `ktx` in /usr/local/bin), or set KTX=/path/to/ktx.',
    );
  }
}

async function download(url: string, to: string): Promise<void> {
  const res = await fetch(url, { headers: { 'User-Agent': 'slapdash-texture-build' } });
  if (!res.ok) fail(`Download failed (${res.status}): ${url}`);
  writeFileSync(to, Buffer.from(await res.arrayBuffer()));
}

/** Download a set's 1K sources into `dir`; returns the source file per map. */
async function fetchSources(set: TextureSet, dir: string): Promise<Record<string, string>> {
  const out: Record<string, string> = {};
  if (set.source === 'polyhaven') {
    const res = await fetch(`https://api.polyhaven.com/files/${set.assetId}`, {
      headers: { 'User-Agent': 'slapdash-texture-build' },
    });
    if (!res.ok) fail(`Poly Haven has no files for "${set.assetId}" (${res.status}).`);
    const files = (await res.json()) as Record<string, Record<string, Record<string, { url: string }>>>;
    for (const map of set.maps) {
      const entry = files[POLYHAVEN_MAP[map]]?.['1k'];
      const file = entry?.jpg ?? entry?.png;
      if (!file) fail(`Poly Haven "${set.assetId}" has no 1k ${POLYHAVEN_MAP[map]} map.`);
      const to = join(dir, `${map}${file.url.endsWith('.png') ? '.png' : '.jpg'}`);
      await download(file.url, to);
      out[map] = to;
    }
  } else {
    const zip = join(dir, 'source.zip');
    await download(`https://ambientcg.com/get?file=${set.assetId}_1K-JPG.zip`, zip);
    execFileSync('unzip', ['-o', '-q', zip, '-d', dir]);
    for (const map of set.maps) {
      const name = `${set.assetId}_1K-JPG_${AMBIENTCG_MAP[map]}.jpg`;
      if (!readdirSync(dir).includes(name)) fail(`ambientCG "${set.assetId}" has no ${AMBIENTCG_MAP[map]} map.`);
      out[map] = join(dir, name);
    }
  }
  return out;
}

function attribution(sets: readonly TextureSet[]): string {
  const lines = [
    '# Texture attribution',
    '',
    'Generated by `scripts/build-textures.ts` from `manifest.json`; do not edit by hand.',
    '',
    'Every texture here is CC0 1.0 (public domain dedication). CC0 needs no attribution, but',
    'we credit the authors anyway. The sources were downscaled to 1K and encoded to KTX2.',
    '',
    '| Set | Asset | Author | Source | Licence | Fetched |',
    '|---|---|---|---|---|---|',
  ];
  for (const s of sets) {
    const site = s.source === 'polyhaven' ? 'Poly Haven' : 'ambientCG';
    lines.push(`| \`${s.id}\` | ${s.name} | ${s.author} | [${site}: ${s.assetId}](${s.url}) | CC0 1.0 | ${s.fetchedOn} |`);
  }
  return `${lines.join('\n')}\n`;
}

function folderBytes(dir: string): number {
  let total = 0;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const st = statSync(p);
    total += st.isDirectory() ? folderBytes(p) : st.size;
  }
  return total;
}

async function main(): Promise<void> {
  const manifest = zTextureManifest.parse(JSON.parse(readFileSync(join(ROOT, 'manifest.json'), 'utf8')));
  const wanted = process.argv.slice(2);
  const unknown = wanted.filter((id) => !manifest.sets.some((s) => s.id === id));
  if (unknown.length > 0) fail(`Not in the manifest: ${unknown.join(', ')}`);
  const sets = wanted.length > 0 ? manifest.sets.filter((s) => wanted.includes(s.id)) : manifest.sets;

  checkKtx();
  let tooBig = false;
  for (const set of sets) {
    const tmp = mkdtempSync(join(tmpdir(), `slapdash-tex-${set.id}-`));
    try {
      console.log(`${set.id}: fetching ${set.source} ${set.assetId}`);
      const sources = await fetchSources(set, tmp);
      const outDir = join(ROOT, set.id);
      rmSync(outDir, { recursive: true, force: true });
      mkdirSync(outDir, { recursive: true });
      for (const map of set.maps) {
        const out = join(outDir, `${map}.ktx2`);
        execFileSync(KTX, ['create', ...ENCODE[map], sources[map]!, out], { stdio: 'inherit' });
        const size = statSync(out).size;
        console.log(`  ${map}.ktx2  ${(size / 1024).toFixed(0)} KB`);
        if (size > MAX_FILE_BYTES) {
          console.error(`  ${set.id}/${map}.ktx2 is over the 1.5 MB per-file budget.`);
          tooBig = true;
        }
      }
    } finally {
      rmSync(tmp, { recursive: true, force: true });
    }
  }

  writeFileSync(join(ROOT, 'ATTRIBUTION.md'), attribution(manifest.sets));
  const total = folderBytes(ROOT);
  console.log(`textures/: ${(total / 1024 / 1024).toFixed(1)} MB`);
  if (total > MAX_TOTAL_BYTES) fail('textures/ is over the 35 MB budget.');
  if (tooBig) fail('Some files are over the per-file budget.');
}

await main();
